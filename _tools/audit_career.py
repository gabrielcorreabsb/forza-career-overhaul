DATA_FILES = ("career", "ladders", "tracks", "track_events", "posters",
              "denylist", "cars", "divisions_full", "divisions", "ids",
              "kits_state", "_meta")


def snapshot_date(snap):
    m = re.match(r"^(\d{4})(\d{2})(\d{2})t", snap or "")
    return (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else None


def build_ctx(args):
    data = {k: read_json(os.path.join(DATA, k + ".json")) for k in DATA_FILES}
    missing = [k for k, v in data.items() if v is None]
    if missing:
        warn("_data ausente para: %s (rode `python _tools\\inventory.py`)"
             % ", ".join(missing))
    cache = load_cache(args.cache_dir)
    ctx = {"live": cache is not None, "data": data,
           "cars": data.get("cars") or [],
           "kits_state": data.get("kits_state") or {},
           "divisions": data.get("divisions"),
           "ids_live": (data.get("ids") or {}).get("live"),
           "track_events_n": (len(data.get("track_events"))
                              if data.get("track_events") is not None else None),
           "xml_extra": None,
           "bcs": None, "names": None, "overrides": None,
           "override_tracks": None, "denied": None, "xml_series_ids": None,
           "prod_names": None, "deny_raw": [], "xml_text": None,
           "override_list": [],
           "ftue": collections.OrderedDict(
               [("present", False), ("championship", None),
                ("championships", 0), ("series", []), ("config", None),
                ("path", FTUE_SCHEDULE)]),
           "xml_schema": None, "featured": collections.OrderedDict(
               [("present", False), ("championship", None),
                ("championships", 0), ("series", []), ("collections", []),
                ("types", []), ("path", RACERS)]),
           "source_label_public": "the local game database and career "
                                  "schedule (read-only audit)"}
    if cache is not None:
        snap, prod, payloads = cache
        bcs = payload_json(payloads, BCS)
        if bcs is None:
            warn("sem BCS na snapshot live - impossivel auditar (leitura "
                 "somente; nada foi escrito)")
            raise SystemExit(1)
        ctx["bcs"] = bcs
        ctx["snapshot"] = snap
        ctx["prod_names"] = {f.get("Path") for f in prod.get("Files") or []}
        ctx["model"] = model_from_bcs(bcs)
        if fstrs.LOGICAL_PT in payloads:
            ctx["names"] = StrTable.load(
                cms_decrypt(payloads[fstrs.LOGICAL_PT])).values_by_name()
        else:
            warn("%s ausente na snapshot - IDS_ nao conferidos"
                 % fstrs.LOGICAL_PT)
        ovr = payload_json(payloads, OVR_LOGICAL)
        if ovr is not None:
            ctx["overrides"] = {o.get("ID"): o for o in ovr}
            ctx["override_list"] = list(ovr)
            ctx["override_tracks"] = {o.get("Track") for o in ovr}
        deny = payload_json(payloads, "CarDenyLists.json")
        if deny is not None:
            ctx["denied"] = {c for e in deny.get("DeniedCars") or []
                             if e.get("AlwaysDeny")
                             for c in (e.get("DeniedCars") or [])}
            ctx["deny_raw"] = list(deny.get("DeniedCars") or [])
        ctx["featured"] = load_featured(payloads)
        ctx["ftue"] = load_ftue(payloads)
        ctx["flags"] = payload_json(payloads,
                                    "ClientFeatureFlagConfiguration.json")
        if XML_LOGICAL in payloads:
            try:
                raw_xml = cms_decrypt(payloads[XML_LOGICAL]).decode("utf-8-sig")
                ctx["xml_series_ids"] = xml_series_ids(raw_xml)
                ctx["xml_text"] = raw_xml
            except (UnicodeDecodeError, ValueError) as exc:
                warn("%s ilegivel (%s) - checagem de entradas pulada"
                     % (XML_LOGICAL, exc))
        if ctx["xml_series_ids"] is not None:
            ctx["xml_extra"] = sorted(set(ctx["xml_series_ids"]) -
                                      {s["id"] for s in ctx["model"]["series"]})
        ctx["source_label"] = ("cache live, snapshot `%s`" % snap)
        ctx["ref_date"] = snapshot_date(snap)
    else:
        ctx["snapshot"] = (data.get("_meta") or {}).get("live_snapshot")
        ctx["model"] = model_from_data(data)
        deny = data.get("denylist") or []
        ctx["denied"] = {c for e in deny if e.get("sempre")
                         for c in (e.get("carros") or [])}
        ctx["source_label"] = ("_data/*.json (modo offline; snapshot `%s`)"
                               % (ctx["snapshot"] or "n/d"))
        ctx["ref_date"] = snapshot_date(ctx["snapshot"])
    ctx["xml_schema"] = xml_schema(ctx["xml_text"]) if ctx["xml_text"] else None
    ref = ctx["ref_date"]
    ctx["ref_tuple"] = ref
    ctx["ref_date"] = ("%04d-%02d-%02d" % ref) if ref else None
    if ctx["names"] is not None:
        ctx["label"] = lambda key: ctx["names"].get(key, key)
    else:
        ctx["label"] = lambda key: key
    return ctx


def render(ctx, counts, diverg, res, rows, tables):
    model = ctx["model"]
    files = collections.OrderedDict()
    files[os.path.relpath(os.path.join(AUDIT_DIR, "SERIES_TABLE.md"), ROOT)] = \
        csv_text(rows)
    files[os.path.relpath(os.path.join(AUDIT_DIR, "SERIES.md"), ROOT)] = \
        "\n".join(md_series(model, ctx, res, rows)) + "\n"
    files[os.path.relpath(os.path.join(AUDIT_DIR, "CUPS.md"), ROOT)] = \
        "\n".join(md_cups(model, ctx, res, counts, diverg)) + "\n"
    files[os.path.relpath(os.path.join(AUDIT_DIR, "SCHEMA_OBSERVED.md"),
                          ROOT)] = \
        "\n".join(md_schema_observed(model, ctx, tables)) + "\n"
    files[os.path.relpath(os.path.join(PUBLIC_DIR, "CARS.md"), ROOT)] = \
        "\n".join(md_cars_public(ctx["cars"], ctx)) + "\n"
    files[os.path.relpath(os.path.join(PUBLIC_DIR, "TRACKS.md"), ROOT)] = \
        "\n".join(md_tracks_public(model, ctx)) + "\n"
    files[os.path.relpath(os.path.join(PUBLIC_DIR, "ENUMS.md"), ROOT)] = \
        "\n".join(md_enums_public(ctx)) + "\n"
    # docs/reference/SCHEMA_REFERENCE.md is a prose doc of the docs agent: never written,
    # never checked here.
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(prog="audit_career.py",
                                 description="read-only career audit")
    ap.add_argument("--cache-dir", default=DEFAULT_CACHE)
    ap.add_argument("--check", action="store_true",
                    help="compare with files on disk, write nothing")
    args = ap.parse_args(argv)

    ctx = build_ctx(args)
    model = ctx["model"]
    print("fonte / source: %s" % ctx["source_label"])
    # tracks/posters come from the raw model, not from _data
    tracks_used = {e["track"] for e in model["events"]}
    posters_used = {s["poster"] for s in model["series"] if s["poster"]}
    counts = count_all(model, ctx["cars"], tracks_used, posters_used)
    diverg = divergences(counts)
    res = audit(model, ctx)
    rows = series_rows(model, ctx, res)
    tables = schema_tables(model, ctx)
    files = render(ctx, counts, diverg, res, rows, tables)

    stale = []
    for rel, text in files.items():
        path = os.path.join(ROOT, rel)
        cur = None
        if os.path.isfile(path):
            # universal newlines: the checkout may have CRLF (core.autocrlf)
            with open(path, "r", encoding="utf-8") as fh:
                cur = fh.read()
        if cur != text:
            stale.append(rel)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="") as fh:
                    fh.write(text)

    errors = [c for c in res["checks"] if c["severity"] == "erro"]
    warns = [c for c in res["checks"] if c["severity"] == "aviso"]
    print("contagens / counts: " + ", ".join(
        "%s=%s" % (k, v) for k, v in counts.items()))
    bad = [d for d in diverg if d["status"] != "ok"]
    print("divergencias vs baseline: %s" % (("%d" % len(bad)) if bad else "0"))
    for c in errors:
        print("ERRO: %s - %s" % (c["id"], c["detail"]))
    for c in warns:
        print("AVISO: %s - %s" % (c["id"], c["detail"]))

    if args.check:
        if stale:
            print("STALE (rode / run `python _tools\\audit_career.py`):")
            for rel in stale:
                print("  " + rel)
            return 1
        print("audit up to date")
        return 1 if errors else 0
    print("written: %d file(s)%s" % (len(stale), "" if not stale else
                                     "\n  " + "\n  ".join(stale)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
