def entry_summary(entry):
    if entry is None:
        return "n/d"
    ec = entry
    lad = ec.get("RequiredLadders") or []
    ser = ec.get("RequiredSeries") or []
    evt = ec.get("RequiredEvents") or []
    lvl = ec.get("MinDriverLevel") or 0
    if not (lad or ser or evt or lvl):
        return "livre"
    return "lvl=%d lad=%s ser=%s evt=%s" % (lvl, lad or 0, ser or 0, evt or 0)


def series_rows(model, ctx, res):
    ref = ctx["ref_tuple"]
    rows = []
    for s in sorted(model["series"],
                    key=lambda x: (x["cup"] or 0, x["ladder"] or 0, x["id"])):
        anom = []
        if not s["name"]:
            anom.append("nome-vazio")
        if not s["poster"]:
            anom.append("poster-vazio")
        if not s["events"]:
            anom.append("sem-evento")
        if is_expired(s["close"], ref):
            anom.append("fechada")
        pi0 = sum(1 for e in s["events"] if not e.get("pi"))
        if pi0:
            anom.append("pi-nulo:%d" % pi0)
        laps0 = sum(1 for e in s["events"] if not e.get("laps"))
        if laps0:
            anom.append("laps-nulo:%d" % laps0)
        ev_custom = [e["id"] for e in s["events"]
                     if fids.is_custom_event(e["id"])]
        if s["id"] >= fids.SERIES_MIN and not ev_custom:
            anom.append("custom-sem-evento-custom")
        if s["id"] < fids.SERIES_MIN and ev_custom:
            anom.append("vanilla-com-evento-custom")
        if s["ordered"] and s["ordered"] != [e["id"] for e in s["events"]]:
            anom.append("ordem-divergente")
        refs = []
        evs = {e["id"] for e in s["events"]}
        for i in s["ordered"]:
            if i not in evs:
                refs.append("OrderedEventIds:%d" % i)
        if ctx["overrides"] is not None:
            for e in s["events"]:
                if e["id"] not in ctx["overrides"]:
                    refs.append("sem-override:%d" % e["id"])
        ids_aus = []
        if ctx["names"] is not None and s["name"] and s["name"] not in ctx["names"]:
            ids_aus.append(s["name"])
        rows.append(collections.OrderedDict([
            ("cup", s["cup"]), ("ladder", s["ladder"]), ("series", s["id"]),
            ("name", ctx["label"](s["name"])),
            ("custom", s["id"] >= fids.SERIES_MIN),
            ("division", s["division"]), ("poster", basename(s["poster"])),
            ("event_count", len(s["events"])),
            ("event_ids", ";".join(str(e["id"]) for e in s["events"])),
            ("tracks", ";".join(str(t) for t in sorted(
                {e["track"] for e in s["events"]}))),
            ("laps_list", "/".join(str(e.get("laps")) for e in s["events"])),
            ("pi_list", "/".join(str(e.get("pi")) for e in s["events"])),
            ("points_list", "/".join(str(e.get("points")) for e in s["events"])
             if any(e.get("points") is not None for e in s["events"]) else "n/d"),
            ("practice_list", "/".join(str(e.get("practice"))
                                       for e in s["events"])
             if any(e.get("practice") is not None for e in s["events"])
             else "n/d"),
            ("car_class", (s["selectable"] or {}).get("CarClassId", "n/d")),
            ("pi_min", (s["selectable"] or {}).get("PIMin", "n/d")),
            ("pi_max", (s["selectable"] or {}).get("PIMax", "n/d")),
            ("car_list_type",
             (s["selectable"] or {}).get("BlockOrAcceptlistType", "n/d")),
            ("car_list_n", len((s["selectable"] or {})
                               .get("BlockOrAcceptlist") or [])
             if s["selectable"] else "n/d"),
            ("ai_cars", s["ai_cars"] if s["ai_cars"] is not None else "n/d"),
            ("series_type", s["series_type"] or "n/d"),
            ("max_players", (s["overrides"] or {}).get("MaxPlayers", "n/d")),
            ("ai_difficulty", (s["overrides"] or {}).get("AIDifficulty", "n/d")),
            ("close", short_date(s["close"])), ("open", short_date(s["open"])),
            ("entry_summary", entry_summary(s["entry"])),
            ("premiar", "n/a-BCS-sem-premio"),
            ("anomalias", ";".join(anom) or "-"),
            ("ids_ausente", ";".join(ids_aus) or "-"),
            ("refs_orfas", ";".join(refs) or "-")]))
    return rows


def csv_text(rows):
    """A tabela por serie como .md (o repo guarda tabelas em .md, nunca .csv)."""
    lines = ["# Series table", "",
             "> Gerado por audit_career.py - nao editar. Uma linha por serie "
             "do championship 500.", ""]
    lines += mdtable.table(CSV_COLS, [[row.get(c, "") for c in CSV_COLS]
                                      for row in rows])
    return "\n".join(lines) + "\n"


