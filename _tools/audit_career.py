    L += ["> Verified: %d cars in the game database; %d have a showroom listing "
          "(%d engine swaps have none)." % (len(cars), n_use + n_deny, n_swap),
          "> Observed: %d always-denied, %d engine swaps, %d career-eligible."
          % (n_deny, n_swap, n_use),
          "> The career car filter resolves to a single `Open` division, so "
          "every non-denied showroom car is career-eligible.",
          "> Reproduce: `python _tools/inventory.py` then "
          "`python _tools/audit_career.py`.",
          "",
          "| CarId | Car | Class | PI | Year | Price | Status | Reason |",
          "|---:|---|:-:|---:|---:|---:|---|---|"]
    for c, status, reason in sorted(stated,
                                    key=lambda x: (x[0].get("class", 0),
                                                   x[0].get("price", 0),
                                                   x[0].get("id", 0))):
        L.append("| %d | %s | %s | %s | %s | %s | %s | %s |" % (
            c.get("id"), c.get("short") or c.get("name") or "?",
            CLASSES.get(c.get("class"), c.get("class")), c.get("pi"),
            c.get("year"), c.get("price"), status, reason))
    return L


