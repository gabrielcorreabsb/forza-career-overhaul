def count_all(model, cars, tracks_used, posters_used):
    cups = model["cups"]
    ladders = [l for c in cups for l in c["ladders"]]
    series = model["series"]
    custom_cups = [c for c in cups if c["id"] != 103]
    vanilla_ladders = [l for c in cups if c["id"] != 103 for l in c["ladders"]]
    cust_s = [s for s in series if s["id"] >= fids.SERIES_MIN]
    van_s = [s for s in series if s["id"] < fids.SERIES_MIN]
    ev_custom = [e for e in model["events"] if fids.is_custom_event(e["id"])]
    return collections.OrderedDict([
        ("cups_vanilla", len(custom_cups)), ("cups_total", len(cups)),
        ("ladders_vanilla", len(vanilla_ladders)),
        ("ladders_total", len(ladders)),
        ("series_vanilla", len(van_s)), ("series_custom", len(cust_s)),
        ("series_total", len(series)),
        ("events_vanilla", len(model["events"]) - len(ev_custom)),
        ("events_custom", len(ev_custom)),
        ("events_total", len(model["events"])),
        ("cars", len(cars or [])),
        ("cars_showroom", len([c for c in (cars or [])
                               if c.get("make") != fcars.SWAP_MAKE
                               and c.get("id") not in fcars.SWAP_IDS])),
        ("tracks", len(tracks_used)), ("posters", len(posters_used)),
        ("posters_uses", len(series))])


def divergences(counts):
    out = []
    for key, want in EXPECTED.items():
        got = counts.get(key)
        out.append({"item": key, "expected": want, "observed": got,
                    "status": "ok" if got == want else "divergente"})
    return out


def doc_divergences(counts):
    out = []
    for key, claimed in DOC_CLAIMS.items():
        out.append({"item": "docs/inventario " + key, "expected": claimed,
                    "observed": counts.get(key),
                    "status": "ok" if counts.get(key) == claimed
                    else "divergente"})
    for key, claimed in KNOWN_STALE.items():
        out.append({"item": "ANALISE 9.2 (obsoleto) " + key,
                    "expected": claimed, "observed": counts.get(key),
                    "status": "obsoleto"})
    return out


