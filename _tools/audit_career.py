def md_tracks_public(model, ctx):
    names = collections.defaultdict(collections.Counter)
    total = collections.Counter()
    for e in model["events"]:
        total[e["track"]] += 1
        if e["name"]:
            names[e["track"]][e["name"]] += 1
    L = md_header("Tracks (%d)" % len(total), ctx, public=True)
    L += ["> Verified: %d track layouts carry at least one career event; "
          "observed %d career events in total." % (len(total),
                                                   sum(total.values())),
          "> Reproduce: `python _tools/inventory.py` then "
          "`python _tools/audit_career.py`.",
          "> One row per `SerialTrackId`; the label is the most common event "
          "name on that layout.", "",
          "| SerialTrackId | Track / layout | Career events |",
          "|---:|---|---:|"]
    for serial in sorted(total, key=lambda s: (names[s].most_common(1)[0][0]
                                               if names[s] else "", s)):
        label = "-"
        if names[serial]:
            label = sorted(names[serial].items(),
                           key=lambda kv: (-kv[1], kv[0]))[0][0]
        L.append("| %d | %s | %d |" % (serial, label, total[serial]))
    return L


