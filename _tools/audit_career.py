def override_facts(model, ctx):
    """1086 records: which ones match a career event, which are foreign."""
    if not ctx["override_list"]:
        return None
    by = collections.Counter(o.get("ID") for o in ctx["override_list"])
    eids = {e["id"] for e in model["events"]}
    matched = {i: n for i, n in by.items() if i in eids}
    unmatched = {i: n for i, n in by.items() if i not in eids}
    dist = collections.Counter(matched.values())
    cls_m = collections.Counter(o.get("ClassRestriction")
                                for o in ctx["override_list"]
                                if o.get("ID") in eids)
    cls_u = collections.Counter(o.get("ClassRestriction")
                                for o in ctx["override_list"]
                                if o.get("ID") not in eids)
    multi = sorted(i for i, n in matched.items() if n > 1)
    return collections.OrderedDict([
        ("registros", len(ctx["override_list"])),
        ("ids_unicos", len(by)),
        ("batem_eventos", len(matched)),
        ("registros_que_batem", sum(matched.values())),
        ("eventos_x1", dist.get(1, 0)),
        ("eventos_variantes", len(multi)),
        ("distribuicao", "x1: %d evento(s); x%d: %d evento(s)"
         % (dist.get(1, 0), max(dist) if dist else 0,
            dist.get(max(dist) if dist else 0, 0))),
        ("variantes", multi),
        ("sem_match_ids", len(unmatched)),
        ("sem_match_registros", sum(unmatched.values())),
        ("sem_override", len(eids - set(by))),
        ("classrestriction_carreira", dict(sorted(cls_m.items()))),
        ("classrestriction_fora", dict(sorted(cls_u.items())))])


