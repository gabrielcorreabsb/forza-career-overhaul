def load_cache(cache_dir):
    """(snap, prod, payloads) or None when the cache is unavailable."""
    try:
        _snaps, snap, _ck, prod, payloads = inventory.load_live(
            os.path.abspath(cache_dir))
    except (SystemExit, OSError, ValueError) as exc:
        warn("cache indisponivel / unavailable (%s) - modo offline com _data/"
             % exc)
        return None
    return snap, prod, payloads


def payload_json(payloads, name):
    try:
        return inventory.dec_json(payloads, name)
    except SystemExit:
        warn("%s ausente na snapshot live - checagens dependentes puladas"
             % name)
        return None


