def read_json(path, default=None):
    if not os.path.isfile(path):
        return default
    with open(path, "r", encoding="utf-8-sig") as fh:
        return json.load(fh)


def parse_dt(value):
    """'2025-6-25 23:59:59.0' -> (2025, 6, 25); None when unusable."""
    if not isinstance(value, str):
        return None
    date = value.split(" ")[0]
    parts = date.split("-")
    if len(parts) != 3:
        return None
    try:
        return tuple(int(x) for x in parts)
    except ValueError:
        return None


def is_expired(value, ref):
    d = parse_dt(value)
    return bool(d and ref and d < ref)


def short_date(value):
    d = parse_dt(value)
    if not d:
        return value or "-"
    if d == (1, 1, 1):
        return "sempre"
    return "%04d-%02d-%02d" % d


