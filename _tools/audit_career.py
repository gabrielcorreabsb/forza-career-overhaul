def portability(ser):
    """Can this Featured series be reproduced in single-player (BCS 500)?"""
    raw = ser["raw"]
    events = [e["raw"] for e in ser["events"]]
    checks = collections.OrderedDict([
        ("SelectableCars", bool(raw.get("SelectableCars"))),
        ("AISelectableCars", bool(raw.get("AISelectableCars"))),
        ("OrderedEventIds", bool(raw.get("OrderedEventIds"))),
        ("SerialTrackId", any(e.get("SerialTrackId") for e in events)),
        ("TargetPI", any(e.get("TargetPI") for e in events)),
        ("NumberOfRequiredLaps", any(e.get("NumberOfRequiredLaps")
                                     for e in events)),
        ("PointSpread", any(e.get("PointSpread") for e in events))])
    missing = [k for k, ok in checks.items() if not ok]
    if not missing:
        return "direto", ""
    if len(missing) >= len(checks) - 1:
        return "inviavel direto", ", ".join(missing)
    return "parcial", ", ".join(missing)


