def model_from_bcs(bcs):
    champs = [c.get("ChampionshipId") for c in bcs.get("Championships") or []]
    hits = [c for c in bcs.get("Championships") or []
            if c.get("ChampionshipId") == CHAMPIONSHIP_CAREER]
    model = {"championships": champs, "career_hits": len(hits),
             "cups": [], "series": [], "events": []}
    career = hits[0] if hits else None
    if career is None:
        return model
    for cup in career.get("ChampionshipCupData") or []:
        cu = {"id": cup.get("ChampionshipCupId"), "name": cup.get("Name") or "",
              "open": cup.get("OpenTime"), "close": cup.get("CloseTime"),
              "entry": entry_of(cup), "champ": cup.get("ChampionshipId"),
              "order": list(cup.get("LadderOrderData") or []), "raw": cup,
              "ladders": []}
        model["cups"].append(cu)
        for lad in cup.get("ChampionshipLadder") or []:
            la = {"cup": cu["id"], "id": lad.get("ChampionshipLadderId"),
                  "name": lad.get("Name") or "", "open": lad.get("OpenTime"),
                  "close": lad.get("CloseTime"), "entry": entry_of(lad),
                  "champ": lad.get("ChampionshipId"),
                  "done": list(lad.get("LadderCompletionRequirements") or []),
                  "order": list(lad.get("OrderData") or []), "raw": lad,
                  "series": []}
            cu["ladders"].append(la)
            for ser in lad.get("ChampionshipSeriesData") or []:
                se = {"cup": cu["id"], "ladder": la["id"],
                      "id": ser.get("ChampionshipSeriesId"),
                      "name": ser.get("Name") or "",
                      "open": ser.get("OpenTime"),
                      "close": ser.get("CloseTime"), "entry": entry_of(ser),
                      "champ": ser.get("ChampionshipId"),
                      "division": (ser.get("SelectableCars") or {}
                                   ).get("CarDivisionId"),
                      "poster": ser.get("ImagePath") or "",
                      "ordered": list(ser.get("OrderedEventIds") or []),
                      "selectable": ser.get("SelectableCars") or {},
                      "ai_cars": len(((ser.get("AISelectableCars") or {})
                                      .get("Acceptlist")) or []),
                      "series_type": ser.get("SeriesType"),
                      "overrides": ser.get("DefaultEventOverrides") or {},
                      "raw": ser,
                      "events": [{"id": e.get("EventDataId"),
                                  "track": e.get("SerialTrackId"),
                                  "name": e.get("Name") or "",
                                  "desc": e.get("Description") or "",
                                  "laps": e.get("NumberOfRequiredLaps"),
                                  "pi": e.get("TargetPI"),
                                  "points": len(e.get("PointSpread") or []),
                                  "practice": e.get(
                                      "OpenPracticeLimitationTimeInSeconds"),
                                  "raw": e}
                                 for e in ser.get("ChampionshipEventData") or []],
                      "type": ser.get("SeriesType")}
                la["series"].append(se)
                model["series"].append(se)
                model["events"] += se["events"]
    return model


def model_from_data(data):
    """Offline model built from _data/*.json (no entry criteria, no raw
    OrderData beyond ladders.json, no IDS_ table)."""
    career = data.get("career") or []
    lad_meta = {}
    for row in data.get("ladders") or []:
        lad_meta[(row.get("cup"), row.get("ladder"))] = row
    model = {"championships": None, "career_hits": 1 if career else 0,
             "cups": [], "series": [], "events": []}
    for cup in career:
        cu = {"id": cup.get("cup"), "name": cup.get("name") or "",
              "open": None, "close": cup.get("close"), "entry": None,
              "champ": None, "order": [], "ladders": []}
        model["cups"].append(cu)
        for lad in cup.get("ladders") or []:
            meta = lad_meta.get((cu["id"], lad.get("ladder"))) or {}
            la = {"cup": cu["id"], "id": lad.get("ladder"),
                  "name": lad.get("name") or "", "open": None,
                  "close": meta.get("close"), "entry": None, "champ": None,
                  "done": [], "order": list(meta.get("order") or []),
                  "series": []}
            cu["ladders"].append(la)
            cu["order"].append(la["id"])
            for ser in lad.get("series") or []:
                se = {"cup": cu["id"], "ladder": la["id"],
                      "id": ser.get("series"), "name": ser.get("name") or "",
                      "open": None, "close": None, "entry": None,
                      "champ": None, "division": ser.get("division"),
                      "poster": ser.get("poster") or "", "ordered": [],
                      "selectable": {}, "ai_cars": None, "series_type": None,
                      "overrides": {}, "raw": None,
                      "type": None,
                      "events": [{"id": e.get("event"), "track": e.get("track"),
                                  "name": e.get("name") or "", "desc": "",
                                  "laps": e.get("laps"), "pi": e.get("pi"),
                                  "points": None, "practice": None,
                                  "raw": None}
                                 for e in ser.get("events") or []]}
                la["series"].append(se)
                model["series"].append(se)
                model["events"] += se["events"]
    return model


