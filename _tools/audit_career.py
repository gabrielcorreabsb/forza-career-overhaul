def load_featured(payloads):
    """Championship 1 (Featured/Multiplayer): series live under SeriesTypeData
    -> SeriesCollections -> Scheduled/CycledSeriesData, plus FTUESeries.
    Missing file => empty model + warning (nothing is invented)."""
    out = collections.OrderedDict([
        ("present", False), ("championship", None), ("championships", 0),
        ("series", []), ("collections", []), ("types", []), ("path", RACERS)])
    raw = payload_json(payloads, RACERS)
    if raw is None:
        return out
    champs = raw.get("Championships") or []
    ch = next((c for c in champs if c.get("ChampionshipId") == 1), None)
    if ch is None:
        warn("%s sem ChampionshipId=1 - Featured fica vazio" % RACERS)
        return out
    out["present"] = True
    out["championship"] = ch
    out["championships"] = len(champs)
    if ch.get("ChampionshipSeriesData"):
        warn("%s: ChampionshipSeriesData inesperadamente nao vazio (%d)"
             % (RACERS, len(ch["ChampionshipSeriesData"])))

    def add_series(ser, source, type_key=None, coll=None):
        out["series"].append({
            "id": ser.get("ChampionshipSeriesId"), "raw": ser,
            "source": source, "type": type_key, "collection": coll,
            "events": [{"id": e.get("EventDataId"), "raw": e}
                       for e in ser.get("ChampionshipEventData") or []]})

    ftue = ch.get("FTUESeries")
    if isinstance(ftue, dict) and ftue.get("ChampionshipSeriesId"):
        add_series(ftue, "ftue")
    for stype in ch.get("SeriesTypeData") or []:
        out["types"].append({"raw": stype, "name": stype.get("SeriesTypeName")})
        for coll in stype.get("SeriesCollections") or []:
            out["collections"].append({"raw": coll,
                                       "type": stype.get("SeriesTypeName")})
            for ser in coll.get("ScheduledSeriesData") or []:
                add_series(ser, "scheduled", stype.get("SeriesTypeName"),
                           coll.get("SeriesCollectionName"))
            for ser in coll.get("CycledSeriesData") or []:
                add_series(ser, "cycled", stype.get("SeriesTypeName"),
                           coll.get("SeriesCollectionName"))
    return out


